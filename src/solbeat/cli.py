"""Command-line interface for SolBeat."""

from __future__ import annotations

import argparse
import json
import os
import sqlite3
import sys
import tempfile
from pathlib import Path
from typing import Any, Sequence

from . import __version__
from .config import PACKAGE_ROOT, load_settings
from .store import EventStore


def _json(value: Any) -> None:
    print(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")))


def _payload(raw: str | None) -> Any:
    if raw is None:
        return None
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"payload must be valid JSON (line {exc.lineno}, column {exc.colno})"
        ) from exc


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="solbeat",
        description="Durable, quiet signal gate for local agents.",
    )
    parser.add_argument(
        "--version", action="version", version=f"%(prog)s {__version__}"
    )
    parser.add_argument("--config", help="TOML policy path (or SOLBEAT_CONFIG)")
    parser.add_argument("--home", help="owner-only state directory (or SOLBEAT_HOME)")
    subparsers = parser.add_subparsers(dest="command", required=True)

    subparsers.add_parser("init", help="create or validate the state database")

    emit = subparsers.add_parser("emit", help="add a bounded, redacted event")
    emit.add_argument("--source", required=True)
    emit.add_argument("--kind", required=True)
    emit.add_argument("--summary", required=True)
    emit.add_argument("--priority", type=int, default=50)
    emit.add_argument("--dedupe-key")
    emit.add_argument("--payload-json")
    emit.add_argument("--delay-seconds", type=int, default=0)

    subparsers.add_parser(
        "gate", help="lease ready events and print one wake-gate JSON line"
    )

    ack = subparsers.add_parser("ack", help="complete every event in a lease")
    ack.add_argument("lease_id")
    ack.add_argument("--receipt", default="completed")

    release = subparsers.add_parser("release", help="release a lease for bounded retry")
    release.add_argument("lease_id")
    release.add_argument("--reason", required=True)
    release.add_argument("--delay-seconds", type=int)

    pause = subparsers.add_parser("pause", help="stop leasing without deleting events")
    pause.add_argument("--reason", default="operator request")
    pause.add_argument(
        "--for-minutes",
        type=int,
        metavar="MINUTES",
        help="resume automatically on the first gate after this many minutes",
    )
    subparsers.add_parser("resume", help="resume leasing")
    subparsers.add_parser("status", help="show content-free queue health as JSON")
    subparsers.add_parser(
        "doctor", help="check schema, integrity, and file permissions"
    )

    install = subparsers.add_parser(
        "install-hermes",
        help="install the physical wake-gate shim required by a Hermes profile",
    )
    install.add_argument("--hermes-home", required=True)
    return parser


def _install_hermes_shim(
    *, hermes_home: Path, config_path: Path, state_home: Path
) -> Path:
    hermes_home = hermes_home.expanduser().resolve()
    scripts = hermes_home / "scripts"
    scripts.mkdir(mode=0o700, parents=True, exist_ok=True)
    os.chmod(hermes_home, 0o700)
    os.chmod(scripts, 0o700)
    target = scripts / "solbeat_gate.py"
    if target.is_symlink():
        raise ValueError(f"refusing to replace symlink: {target}")
    marker = "# Generated by SolBeat install-hermes; safe to refresh."
    if target.exists():
        first_line = target.read_text(encoding="utf-8").splitlines()[:2]
        if marker not in first_line:
            raise ValueError(f"refusing to replace an unmanaged file: {target}")
    interpreter = Path(sys.executable).expanduser().resolve()
    interpreter_text = str(interpreter)
    if (
        not interpreter.is_file()
        or not os.access(interpreter, os.X_OK)
        or any(character.isspace() for character in interpreter_text)
    ):
        raise ValueError(
            "current Python interpreter cannot be pinned in a portable shebang: "
            f"{interpreter}"
        )
    import_root = PACKAGE_ROOT.parent
    document = "\n".join(
        (
            f"#!{interpreter_text}",
            marker,
            "from __future__ import annotations",
            "import sys",
            f"sys.path.insert(0, {str(import_root)!r})",
            "from solbeat.cli import main",
            f"raise SystemExit(main(['--config', {str(config_path)!r}, '--home', {str(state_home)!r}, 'gate']))",
            "",
        )
    )
    fd, temporary_name = tempfile.mkstemp(
        prefix=".solbeat_gate.", dir=scripts, text=True
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(document)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary_name, 0o700)
        os.replace(temporary_name, target)
    finally:
        if os.path.exists(temporary_name):
            os.unlink(temporary_name)
    return target


def main(argv: Sequence[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    try:
        settings = load_settings(config_path=args.config, home=args.home)
        store = EventStore(settings)
        store.initialize()

        if args.command == "init":
            _json({"initialized": True, "schema": "solbeat.init/v1"})
            return 0
        if args.command == "emit":
            event_id, inserted = store.emit(
                source=args.source,
                kind=args.kind,
                summary=args.summary,
                priority=args.priority,
                payload=_payload(args.payload_json),
                dedupe_key=args.dedupe_key,
                delay_seconds=args.delay_seconds,
            )
            _json(
                {
                    "event_id": event_id,
                    "inserted": inserted,
                    "schema": "solbeat.emit/v1",
                }
            )
            return 0
        if args.command == "gate":
            _json(store.gate().as_dict())
            return 0
        if args.command == "ack":
            result = store.ack(args.lease_id, receipt=args.receipt)
            _json(
                {
                    "completed": result.completed,
                    "handled": result.handled,
                    "requeued": result.requeued,
                    "schema": "solbeat.ack/v1",
                }
            )
            return 0 if result.handled else 3
        if args.command == "release":
            retried, dead = store.release(
                args.lease_id,
                reason=args.reason,
                delay_seconds=args.delay_seconds,
            )
            _json({"dead": dead, "retried": retried, "schema": "solbeat.release/v1"})
            return 0 if retried or dead else 3
        if args.command == "pause":
            duration_seconds = (
                None if args.for_minutes is None else args.for_minutes * 60
            )
            store.set_paused(
                True,
                reason=args.reason,
                duration_seconds=duration_seconds,
            )
            pause_status = store.status()
            _json(
                {
                    "paused": pause_status["paused"],
                    "paused_until": pause_status["paused_until"],
                    "schema": "solbeat.pause/v1",
                }
            )
            return 0
        if args.command == "resume":
            store.set_paused(False, reason="operator resumed")
            _json(
                {
                    "paused": False,
                    "paused_until": None,
                    "schema": "solbeat.resume/v1",
                }
            )
            return 0
        if args.command == "status":
            _json(store.status())
            return 0
        if args.command == "doctor":
            result = store.doctor()
            _json(result)
            return 0 if result["ok"] else 1
        if args.command == "install-hermes":
            target = _install_hermes_shim(
                hermes_home=Path(args.hermes_home),
                config_path=settings.config_path,
                state_home=settings.home,
            )
            _json(
                {
                    "installed": True,
                    "physical_script": str(target),
                    "schema": "solbeat.hermes-install/v1",
                }
            )
            return 0
        parser.error(f"unknown command: {args.command}")
    except (OSError, sqlite3.Error, ValueError) as exc:
        print(f"solbeat: {exc}", file=sys.stderr)
        return 2
    return 2
